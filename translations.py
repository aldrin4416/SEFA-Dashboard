def get_text(lang, key, **kwargs):
    """Return translated string for key, formatted with kwargs.

    Fallback chain: lang → English → key itself.
    """
    text = (
        TRANSLATIONS.get(lang, {}).get(key)
        or TRANSLATIONS["en"].get(key)
        or key
    )
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError):
            return text
    return text

